import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { once } from 'node:events';
import { createPanel } from '../server.mjs';

test('login, CSRF, isolamento do projeto, logs e operações sem remover volumes', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'infra-panel-'));
  const project = path.join(root, 'projects/main'); await fs.mkdir(path.join(project, 'public'), { recursive: true });
  const env = `APP_DIRECTORY=${project}\nAPP_DOMAIN=localhost\nDB_PASSWORD=super-secret-password\nPANEL_PASSWORD=panel-secret-password\n`;
  await fs.writeFile(path.join(root, '.env'), env);
  const calls = [];
  const executor = async (cmd, args) => {
    calls.push(args);
    if (args.includes('config') && args.includes('--format')) return { stdout: JSON.stringify({ name: 'laravel', services: { php: { image: 'laravel-php' }, traefik: { image: 'traefik:v3' }, panel: {} } }) };
    if (args[0] === 'info') return { stdout: '{"cpus":4,"memoryBytes":8589934592}' };
    if (args[0] === 'stats') return { stdout: JSON.stringify({ID:'abc',Name:'php',CPUPerc:'10%',MemUsage:'100MiB / 8GiB',NetIO:'1MB / 1MB',PIDs:'3'}) };
    if (args[0] === 'ps') return { stdout: 'abc\n' };
    if (args[0] === 'inspect') return { stdout: JSON.stringify([{ Id: 'abcdef1234567890', Created: '2026-11-09T09:00:00Z', RestartCount: 2, NetworkSettings: { Ports: { '8000/tcp': null } }, Name: '/php', Config: { Labels: { 'com.docker.compose.service': 'php' } }, State: { Status: 'running', StartedAt: '2026-11-09T10:00:00Z', FinishedAt: '0001-01-01T00:00:00Z', ExitCode: 0, Health: { Status: 'healthy' } }, Mounts: [] }]) };
    if (args[0] === 'volume' && args[1] === 'ls') return { stdout: 'laravel_mariadb_data\n' };
    if (args[0] === 'volume' && args[1] === 'inspect') return { stdout: JSON.stringify([{ Name: 'laravel_mariadb_data', Driver: 'local', Mountpoint: '/var/lib/docker/volumes/laravel_mariadb_data/_data' }]) };
    if (args.includes('exec') && args.includes('sh')) return { stdout: 'PHP test output', stderr: '' };
    if (args.includes('logs')) return { stdout: 'diagnostic super-secret-password' };
    return { stdout: '' };
  };
  const server = createPanel({ root, username: 'paulo', password: 'panel-secret-password', metricsFetcher: async () => ({ ok: true, text: async () => 'traefik_entrypoint_requests_total{entrypoint="web",code="200"} 10\n' }), terminalEnabled: true, executor });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await fs.rm(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const request = (route, options = {}) => fetch(base + route, options);
  assert.equal((await request('/api/status')).status, 401);
  assert.equal((await request('/api/databases/mariadb')).status, 401);
  assert.equal((await request('/api/apps/main/env')).status, 401);
  const login = await request('/api/login', { method: 'POST', body: JSON.stringify({ username: 'paulo', password: 'panel-secret-password' }) });
  assert.equal(login.status, 200);
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const { csrf } = await login.json();
  const headers = { Cookie: cookie, 'X-CSRF-Token': csrf, 'Content-Type': 'application/json' };
  assert.equal((await request('/api/config', { method: 'PUT', headers: { Cookie: cookie }, body: '{}' })).status, 403);
  assert.equal((await request('/api/apps/main/env', { method: 'PUT', headers: { Cookie: cookie }, body: '{}' })).status, 403);
  const envStatus = await request('/api/apps/main/env/status', { headers });
  assert.equal(envStatus.headers.get('cache-control'), 'no-store');
  assert.equal((await envStatus.json()).exists, false);
  const createEnv = await request('/api/apps/main/env', { method: 'PUT', headers, body: JSON.stringify({ content: 'APP_NAME=Sample\n', revision: null, directory: project }) });
  assert.equal(createEnv.status, 200);
  assert.equal((await (await request('/api/apps/main/env', { headers })).json()).content, 'APP_NAME=Sample\n');
  assert.equal((await request('/api/databases/postgres/create-user', { method: 'POST', headers: { Cookie: cookie }, body: '{}' })).status, 403);
  assert.equal((await request('/api/databases/postgres/drop', { method: 'POST', headers, body: '{}' })).status, 404);
  assert.equal((await request('/api/services/php/stop', { method: 'POST', headers: { ...headers, Origin: 'http://evil.invalid' } })).status, 403);
  const statusResponse = await request('/api/status', { headers }); const status = await statusResponse.json();
  assert.equal(statusResponse.status, 200); assert.equal(status.services[0].state, 'running');
  assert.equal(status.volumes[0].name, 'laravel_mariadb_data');
  assert.equal(JSON.stringify(status).includes('super-secret-password'), false);
  assert.equal((await request('/api/services/panel/stop', { method: 'POST', headers })).status, 403);
  assert.equal((await request('/api/services/other-project/stop', { method: 'POST', headers })).status, 403);
  const logs = await (await request('/api/services/php/logs', { headers })).json();
  assert.equal(logs.logs, 'diagnostic [oculto]');
  assert.equal(status.services[0].restartCount, 2);
  assert.equal(status.services[0].containerId, 'abcdef123456');
  assert.equal(status.services[0].startedAt, '2026-11-09T10:00:00Z');
  const metrics = await request('/api/metrics', { headers }); assert.equal(metrics.status, 200); assert.equal((await metrics.json()).current.http.total, 10);
  const command = 'php -v; echo example';
  const terminal = await request('/api/services/php/exec', { method: 'POST', headers, body: JSON.stringify({ shell: 'sh', command }) });
  assert.equal(terminal.status, 200); assert.equal((await terminal.json()).stdout, 'PHP test output');
  const execution = calls.find(args => args.includes(command));
  assert.equal(execution.at(-1), command); assert.ok(execution.includes('exec')); assert.ok(execution.some(arg => arg.includes('timeout -k 2s 25s')));
  assert.equal((await request('/api/services/panel/exec', { method: 'POST', headers, body: JSON.stringify({ shell: 'sh', command: 'id' }) })).status, 403);
  assert.equal((await request('/api/services/unknown/exec', { method: 'POST', headers, body: JSON.stringify({ shell: 'sh', command: 'id' }) })).status, 403);
  const clear = await request('/api/logs/clear', { method: 'POST', headers, body: JSON.stringify({ service: 'php' }) });
  assert.equal(clear.status, 200);
  await request('/api/services/php/logs', { headers });
  assert.ok(calls.some(args => args.includes('logs') && args.includes('--since')));
  assert.equal((await request('/api/logs/clear', { method: 'POST', headers, body: JSON.stringify({ service: 'unrelated' }) })).status, 403);
  const saved = await (await request('/api/config', { headers })).json();
  saved.config.proxy.httpPort = 80;
  saved.config.proxy.databases.mariadb={bindAddress:'0.0.0.0',port:13306};
  const update = await request('/api/config', { method: 'PUT', headers, body: JSON.stringify(saved) });
  assert.equal(update.status, 200); const next = await update.json();
  assert.equal((await request('/api/config', { method: 'PUT', headers, body: JSON.stringify(saved) })).status, 409);
  const apply = await request('/api/apply', { method: 'POST', headers, body: JSON.stringify({ revision: next.revision }) });
  assert.equal(apply.status, 202);
  let operation;
  for (let attempt = 0; attempt < 30; attempt++) {
    operation = (await (await request('/api/operation', { headers })).json()).operation;
    if (operation.state !== 'running') break;
    await new Promise(resolve => setTimeout(resolve, 10));
  }
  assert.equal(operation.state, 'success', operation.message);
  const newEnv = await fs.readFile(path.join(root, '.env'), 'utf8');
  assert.match(newEnv, /MARIADB_PORT='13306'/);assert.match(newEnv, /MARIADB_BIND_ADDRESS='0.0.0.0'/);
  assert.ok(calls.some(args=>args.includes('up')&&args.includes('--force-recreate')&&args.includes('mariadb')));
  assert.match(newEnv, /HTTP_PORT='80'/); assert.match(newEnv, /DB_PASSWORD=super-secret-password/);
  assert.equal(await fs.readFile(path.join(root, '.panel-state/env-before-apply'), 'utf8'), env);
  assert.equal(calls.some(args => args.includes('down') || args.includes('--volumes') || args.includes('-v')), false);
  assert.ok(calls.some(args => args[0] === 'ps' && args.includes('label=com.docker.compose.project=laravel')));
  // Uma alteração de runtime precisa chegar ao override e ao .env através da API.
  await fs.writeFile(path.join(project,'public/index.html'),'<h1>Static</h1>');
  const typed=await (await request('/api/config',{headers})).json();
  Object.assign(typed.config.applications[0],{type:'static',buildDirectory:'public',spa:true});
  const typedSaved=await (await request('/api/config',{method:'PUT',headers,body:JSON.stringify(typed)})).json();
  const typedApply=await request('/api/apply',{method:'POST',headers,body:JSON.stringify({revision:typedSaved.revision})});assert.equal(typedApply.status,202);
  for(let i=0;i<50;i++){operation=(await(await request('/api/operation',{headers})).json()).operation;if(operation.state!=='running')break;await new Promise(r=>setTimeout(r,10));}
  assert.equal(operation.state,'success',operation.message);
  assert.match(await fs.readFile(path.join(root,'config/apps.compose.yaml'),'utf8'),/caddy:/);
  assert.match(await fs.readFile(path.join(root,'.env'),'utf8'),/APP_TYPE='static'/);
  assert.ok(calls.some(args=>args.includes(path.join(root,'config/apps.staged.yaml'))&&args.includes('--quiet')));
  assert.equal(calls.some(args=>args.includes('down')||args.includes('--volumes')),false);

});
